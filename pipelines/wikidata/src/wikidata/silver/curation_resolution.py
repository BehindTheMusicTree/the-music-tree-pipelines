import json
import logging
import re
from pathlib import Path

import polars as pl
from jsonschema import ValidationError, validate

from wikidata.silver.regional_overview_classification import orphan_overview_parent_ids
from wikidata.wikidata_client import EntityInfo, fetch_entities, fetch_labels

logger = logging.getLogger(__name__)

CURATION_RESOLUTIONS_SCHEMA_PATH = Path(__file__).parent.parent / "schemas" / "curation_resolutions.schema.json"

# Wikidata merges (redirects) and deletes items, so a curated QID can vanish from the Bronze genre tree
# between two runs and every downstream inline "not found in the genre tree" check would kill the run.
# This step runs first: a merged QID whose target is known is rewritten in place in the Bronze CSVs
# (regenerated by every curation ingest), anything else is dropped from this run and reported in
# curation_resolutions.json for admin review in grow-the-music-tree-api.
#
# The report's `key` is the row's original grow CurationList.key: item_id alone, except for the lists in
# KEY_COLUMNS, whose key columns grow joins with a tab. Left out: regional_overview_additions (lists items
# absent from Bronze by design), canonical_parent_additions (LOCAL: ids) and regional_secondary_parents
# (Gold, edge-checked).
QID_COLUMNS: dict[str, tuple[str, ...]] = {
    "accepted_canonical_roots": ("item_id",),
    "canonical_overrides": ("item_id",),
    "canonical_parent": ("item_id", "parent_item_id"),
    "duplicate_genres": ("item_id",),
    "indigenous_to_exclusions": ("item_id",),
    "label_overrides": ("item_id",),
    "out_of_scope_genres": ("item_id",),
    "overview_reclassifications": ("item_id",),
    "regional_genre_parent": ("item_id", "parent_item_id"),
    "regional_overviews": ("item_id", "overview_item_id"),
    "technique_genres": ("item_id",),
    "theme_genres": ("item_id",),
    "non_stylistic_genres": ("item_id",),
    "umbrella_genres": ("item_id",),
}
KEY_COLUMNS: dict[str, tuple[str, ...]] = {"regional_overviews": ("item_id", "overview_item_id")}
KEY_SEPARATOR = "\t"
# An item_id may sit in at most one of these (grow's EXCLUSIVE_LISTS).
EXCLUSIVE_LISTS = frozenset({"theme_genres", "technique_genres", "out_of_scope_genres", "duplicate_genres"})
# Items these lists prune never reach the steps that validate a curated parent / overview target.
PRUNING_LISTS = (*EXCLUSIVE_LISTS, "non_stylistic_genres")
# Lists whose items the pipeline adds to the tree itself, so references to them are known.
ADDITION_LISTS = ("regional_overview_additions", "canonical_parent_additions")

_QID_PATTERN = re.compile(r"Q[0-9]+")


def _csv_path(curation_dir: Path, list_name: str) -> Path:
    return curation_dir / f"manual_{list_name}.csv"


def _ids(df: pl.DataFrame, column: str) -> set[str]:
    return {value.strip() for value in df.get_column(column).drop_nulls()}


def _key(list_name: str, row: dict) -> str:
    return KEY_SEPARATOR.join((row[c] or "").strip() for c in KEY_COLUMNS.get(list_name, ("item_id",)))


def _key_conflict(
    list_name: str, row: dict, column: str, target: str, colliding_lists: frozenset[str], keys: dict[str, set[str]]
) -> str | None:
    if column not in KEY_COLUMNS.get(list_name, ("item_id",)):
        return None
    remapped_key = _key(list_name, {**row, column: target})
    return next((other for other in sorted(colliding_lists) if remapped_key in keys[other]), None)


def resolve_curation_qids(
    genre_tree_path: Path, indigenous_to_path: Path, curation_dir: Path, output_dir: Path
) -> Path:
    lists = {name: pl.read_csv(_csv_path(curation_dir, name), infer_schema=False) for name in QID_COLUMNS}
    tree = pl.read_parquet(genre_tree_path)
    tree_ids = set(tree.get_column("item_id"))
    for name in ADDITION_LISTS:
        tree_ids |= _ids(pl.read_csv(_csv_path(curation_dir, name), infer_schema=False), "item_id")
    indigenous_ids = set(pl.read_parquet(indigenous_to_path).get_column("item_id"))

    # Silver promotes orphan "music of X" parents to root rows, so only regional_overviews can target them.
    regional_ids = tree_ids | orphan_overview_parent_ids(tree)

    def reference(list_name: str) -> set[str]:
        if list_name == "indigenous_to_exclusions":
            return indigenous_ids
        return regional_ids if list_name == "regional_overviews" else tree_ids

    unknown = sorted(
        {
            value.strip()
            for name, df in lists.items()
            for column in QID_COLUMNS[name]
            for value in df.get_column(column).drop_nulls()
            if _QID_PATTERN.fullmatch(value.strip()) and value.strip() not in reference(name)
        }
    )
    entities = fetch_entities(unknown) if unknown else {}
    current_ids = {qid: None if info is None else info.id for qid, info in entities.items()}
    class_ids = sorted(
        {
            class_id
            for name, df in lists.items()
            for column in QID_COLUMNS[name]
            for value in df.get_column(column).drop_nulls()
            if (info := entities.get(value.strip())) and info.id not in reference(name)
            for class_id in (*info.instance_of, *info.subclass_of)
        }
    )
    class_labels = fetch_labels(class_ids) if class_ids else {}

    def evidence(info: EntityInfo, reason: str, list_name: str, conflict_list: str | None) -> dict:
        found: dict = {"label": info.label, "modified": info.modified}
        if reason == "not_in_tree":
            found["instanceOf"] = [{"id": c, "label": class_labels[c]} for c in info.instance_of]
            found["subclassOf"] = [{"id": c, "label": class_labels[c]} for c in info.subclass_of]
            if list_name == "indigenous_to_exclusions":
                found["hasIndigenousTo"] = info.has_indigenous_to
        else:
            found["conflictList"] = conflict_list
        return {k: v for k, v in found.items() if v is not None}

    keys = {name: {_key(name, row) for row in df.to_dicts()} for name, df in lists.items()}
    pruned_ids = set().union(*(keys[name] for name in PRUNING_LISTS))
    remaps: list[dict[str, str]] = []
    review: list[dict] = []
    for name, df in lists.items():
        colliding_lists = EXCLUSIVE_LISTS if name in EXCLUSIVE_LISTS else frozenset({name})
        rows = df.to_dicts()
        kept = []
        changed = False
        for row in rows:
            key = _key(name, row)
            row_remaps, row_review = [], []
            for column in QID_COLUMNS[name]:
                qid = (row[column] or "").strip()
                if qid not in current_ids:
                    continue
                target = current_ids[qid]
                entry = {"list": name, "key": key, "column": column}
                info = entities[qid]
                if info is None:
                    row_review.append({**entry, "itemId": qid, "reason": "missing"})
                elif target not in reference(name):
                    redirect = {"target": target} if target != qid else {}
                    row_review.append(
                        {
                            **entry,
                            "itemId": qid,
                            "reason": "not_in_tree",
                            **redirect,
                            "evidence": evidence(info, "not_in_tree", name, None),
                        }
                    )
                elif (key_conflict := _key_conflict(name, row, column, target, colliding_lists, keys)) or (
                    column != "item_id" and (target in pruned_ids or target == (row["item_id"] or "").strip())
                ):
                    if key_conflict:
                        conflict_list = key_conflict
                    elif target in pruned_ids:
                        conflict_list = next(other for other in sorted(PRUNING_LISTS) if target in keys[other])
                    else:
                        conflict_list = name
                    row_review.append(
                        {
                            **entry,
                            "itemId": qid,
                            "reason": "redirect_conflict",
                            "target": target,
                            "evidence": evidence(info, "redirect_conflict", name, conflict_list),
                        }
                    )
                else:
                    row_remaps.append({**entry, "from": qid, "to": target})
            if row_review:
                review.extend(row_review)
                keys[name].discard(key)
                changed = True
                continue
            for remap in row_remaps:
                row[remap["column"]] = remap["to"]
            if row_remaps:
                keys[name].discard(key)
                keys[name].add(_key(name, row))
            remaps.extend(row_remaps)
            changed = changed or bool(row_remaps)
            kept.append(row)
        if changed:
            pl.DataFrame(kept, schema=df.schema).write_csv(_csv_path(curation_dir, name))

    report = {"remaps": remaps, "review": review}
    try:
        validate(report, json.loads(CURATION_RESOLUTIONS_SCHEMA_PATH.read_text()))
    except ValidationError as e:
        raise ValueError(f"curation resolutions failed schema validation ({CURATION_RESOLUTIONS_SCHEMA_PATH}): {e}")
    if remaps:
        logger.info("remapped %d merged curated QID(s): %s", len(remaps), remaps)
    if review:
        logger.warning("dropped %d curated row(s) for admin review: %s", len(review), review)

    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "curation_resolutions.json"
    output_path.write_text(json.dumps(report, indent=2))
    logger.info("wrote %s (%d remap(s), %d review(s))", output_path, len(remaps), len(review))
    return output_path
